/** ?lang=… first, then the browser's languages, else German. */
export function pickLang(param: string | null, browser: readonly string[]): Lang {
  const known = (c: string | null | undefined): Lang | null => {
    const base = (c ?? "").toLowerCase().split(/[-_]/)[0];
    return (LANG_CODES as readonly string[]).includes(base) ? (base as Lang) : null;
  };
  return known(param) ?? browser.map(known).find((x): x is Lang => x !== null) ?? "de";
}

export const fill = (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
