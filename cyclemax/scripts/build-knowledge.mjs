// Compiles /knowledge/*.md into shared/knowledge.generated.ts.
// Run: npm run knowledge  (also runs before build and tests)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "knowledge");
const CATEGORIES = new Set(["any", "yellow", "pink", "green", "red", "single"]);

function fnv1a(text) {
  let h = 0x811c9dc5;
  for (const ch of text) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(36);
}

const lines = [];
const seen = new Set();
for (const raw of readFileSync(join(dir, "daily-lines.md"), "utf8").split("\n")) {
  const m = raw.match(/^- \[(\w+)\] (.+)$/);
  if (!m) continue;
  const [, category, text] = m;
  if (!CATEGORIES.has(category)) throw new Error(`Unknown category ${category}: ${text}`);
  if (seen.has(text)) throw new Error(`Duplicate line: ${text}`);
  seen.add(text);
  lines.push({ id: `s-${fnv1a(text)}`, text: text.trim(), category });
}

const principles = readFileSync(join(dir, "chat-principles.md"), "utf8")
  .split("\n")
  .reduce((acc, l) => {
    if (l.startsWith("- ")) acc.push(l.slice(2).trim());
    else if (l.startsWith("  ") && acc.length) acc[acc.length - 1] += " " + l.trim();
    return acc;
  }, []);

const docs = readdirSync(dir)
  .filter((f) => f.endsWith(".md") && f !== "README.md" && f !== "daily-lines.md")
  .sort()
  .map((f) => {
    const body = readFileSync(join(dir, f), "utf8").trim();
    const title = (body.match(/^# (.+)$/m) || [, f])[1];
    return { slug: f.replace(/\.md$/, ""), title, body };
  });

const out = `// AUTO-GENERATED by scripts/build-knowledge.mjs from /knowledge – do not edit by hand.
import type { KnowledgeDoc, Line } from "./types";

export const SEED_LINES: Line[] = ${JSON.stringify(lines, null, 2)};

export const SEED_PRINCIPLES: string[] = ${JSON.stringify(principles, null, 2)};

export const KNOWLEDGE_DOCS: KnowledgeDoc[] = ${JSON.stringify(docs, null, 2)};
`;
writeFileSync(join(root, "shared", "knowledge.generated.ts"), out);
console.log(`knowledge: ${lines.length} lines, ${principles.length} principles, ${docs.length} docs`);
